LaboratoryTestMapping _mapping(
  String id,
  String network,
  String text,
  String concept,
  String source, {
  String? code,
}) => LaboratoryTestMapping(
  id: id,
  sourceSystem: network,
  sourceText: text,
  conceptId: concept,
  sourceCode: code,
  source: Uri.parse(source),
  checkedAt:
      reviewedLaboratorySpecifications[id]?.checkedAt ?? DateTime(2026, 11, 26),
  specification: reviewedLaboratorySpecifications[id],
);
