"""Embed the reviewed public facts snapshot in the platform-independent package."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'packages/provider_directory/data/catalog.json'
data = json.loads(source.read_text())
assert data['schemaVersion'] == 1
payload = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
assert "'''" not in payload
out = root / 'packages/provider_directory/lib/src/bundled_catalog.dart'
generated = ("// Generated by tool/build_provider_catalog.py. Edit data/catalog.json instead.\n"
               "import 'catalog.dart';\n\n"
               "ProviderCatalog bundledDirectory() => ProviderCatalog.decode(_snapshot);\n\n"
               "const _snapshot =\n    r'''" + payload + "''';\n")
if '--check' in sys.argv:
    if out.read_text() != generated:
        raise SystemExit('Bundled catalogue differs from data/catalog.json; regenerate it.')
    print('Bundled catalogue matches the reviewed source snapshot.')
else:
    out.write_text(generated)
    print(f'Generated {out.relative_to(root)}')
